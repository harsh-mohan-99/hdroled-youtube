"""Embed our static popup markup/styles for an isolated, resource-free page popup."""
from pathlib import Path
import json
import re

root = Path(__file__).resolve().parent.parent / 'extension'
html = (root / 'popup.html').read_text(encoding='utf-8')
main = re.search(r'<main class="shell">[\s\S]*?</main>', html).group()
icon = (root / 'icons/icon.svg').read_text(encoding='utf-8')
icon = re.sub(r'<\?xml[^>]*>', '', icon).strip()
main = main.replace('<img src="icons/icon.svg" alt="">', icon)
css = (root / 'popup.css').read_text(encoding='utf-8')
css = css.replace(':root', '.ui-root')
css = re.sub(r'\bbody\b', '.ui-root', css)
data = {'html': main, 'css': css}
output = '// Generated by scripts/build-panel.py from popup.html, popup.css and icons/icon.svg.\n'
output += 'globalThis.HDROLED_PANEL_TEMPLATE=' + json.dumps(data, ensure_ascii=True, separators=(',', ':')) + ';\n'
(root / 'panel-template.js').write_text(output, encoding='utf-8')
print('Page popup template built from shared toolbar UI.')
